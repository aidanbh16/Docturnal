// --- Small text helpers ---

function hasMarker(content) {
  if (typeof content !== 'string') return false;
  return content.replace(/^\uFEFF/, '').split(/\r?\n/, 1)[0].trim() === MARKER;
}

function stripEmoji(line) {
  if (!line.match(EMOJI)) return line;
  return line.replace(EMOJI, '').replace(/(\S)[ \t]{2,}/g, '$1 ').replace(/[ \t]+$/, '');
}

function firstSentence(text) {
  const clean = stripEmoji(String(text || '').replace(/\s+/g, ' ').trim());
  if (!clean) return '';
  const match = clean.match(/^.*?[.!?](?=\s|$)/);
  const sentence = (match ? match[0] : clean).trim();
  return /[.!?]$/.test(sentence) ? sentence : `${sentence}.`;
}

// A layer's description: one sentence, or, for a part that groups several, the sentence that
// lists them and the one after it (see groupDescription in layers.js).
function layerDescription(text) {
  const first = firstSentence(text);
  if (!/^Holds the project's \d+ (packages|parts): /.test(first)) return first;
  const rest = firstSentence(String(text).replace(/\s+/g, ' ').trim().slice(first.length));
  return rest && rest !== '.' ? `${first} ${rest}` : first;
}

function keepsCase(word) {
  return /[A-Z].*[A-Z]/.test(word) || /\d/.test(word) || /[._/]/.test(word.slice(1, -1));
}

function titleCase(name) {
  const words = stripEmoji(String(name || '')).replace(/[`*_#]/g, '').replace(/\s+/g, ' ').trim().split(' ');
  return words
    .filter(Boolean)
    .map((word, i) => {
      if (keepsCase(word)) return word;
      const lower = word.toLowerCase();
      if (NOUN_MAP.has(lower)) return NOUN_MAP.get(lower);
      if (i > 0 && i < words.length - 1 && SMALL_WORDS.has(lower)) return lower;
      return lower.charAt(0).toUpperCase() + lower.slice(1);
    })
    .join(' ');
}

function sentenceCaseWord(word, isFirst) {
  if (word.includes('`') || !word) return word;
  const [, lead, core, trail] = word.match(/^([^\p{L}\p{N}]*)(.*?)([^\p{L}\p{N}]*)$/u);
  const parts = core.split('-').map((part, i) => {
    const first = isFirst && i === 0;
    if (!part) return part;
    if (NOUN_MAP.has(part.toLowerCase())) return NOUN_MAP.get(part.toLowerCase());
    if (part === 'I' || keepsCase(part)) return part;
    const lower = part.toLowerCase();
    return first ? lower.charAt(0).toUpperCase() + lower.slice(1) : lower;
  });
  return lead + parts.join('-') + trail;
}

function sentenceCase(text) {
  // A heading in all capitals is shouting, not a run of acronyms.
  const source = /[a-z]/.test(text) || !/\s/.test(text.trim()) ? text : text.toLowerCase();
  let first = true;
  return source
    .split(/(\s+)/)
    .map((token) => {
      if (!token.trim()) return token;
      const result = sentenceCaseWord(token, first);
      first = false;
      return result;
    })
    .join('');
}

function cleanHeadingText(text) {
  return stripEmoji(text)
    .replace(/^(\*\*|__)(.*)\1$/, '$2')
    .replace(/^\d+(\.\d+)*[.)]?\s+/, '')
    .replace(/[:.]+$/, '')
    .trim();
}

function tableCell(text) {
  return stripEmoji(String(text || '')).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

function linkPath(from, to) {
  return encodeURI(path.posix.relative(from, to) || '.');
}

// --- Cleaning model output ---

// Removes a code fence that wraps the whole reply, along with any chatter around it.
function unwrapWholeFence(text) {
  const lines = text.split('\n');
  const open = lines.findIndex((line) => /^\s*(```|~~~)\s*(markdown|md)?\s*$/i.test(line));
  if (open === -1) return text;
  const fence = lines[open].trim().slice(0, 3);
  let close = -1;
  for (let i = lines.length - 1; i > open; i--) {
    if (lines[i].trim() === fence) {
      close = i;
      break;
    }
  }
  const isHeading = (line) => /^#{1,6}\s/.test(line);
  const before = lines.slice(0, open);
  const inner = close === -1 ? lines.slice(open + 1) : lines.slice(open + 1, close);
  const after = close === -1 ? [] : lines.slice(close + 1);
  if (before.some(isHeading) || after.some(isHeading) || !inner.some(isHeading)) return text;
  return inner.join('\n');
}

function trimChatter(lines) {
  let start = 0;
  while (start < lines.length && (!lines[start].trim() || CHATTY_LINE.test(lines[start].trim()))) start++;
  let end = lines.length;
  while (end > start && (!lines[end - 1].trim() || CHATTY_LINE.test(lines[end - 1].trim()))) end--;
  return lines.slice(start, end);
}

// Links to files that do not exist become plain text. Anchors are kept, and web links are
// left to links.js.
function fixLinks(line, docPath, existingPaths) {
  if (!existingPaths) return line;
  return line.replace(/(!?)\[([^\]\n]*)\]\(([^)\s]*)(\s+"[^"]*")?\)/g, (match, bang, label, target) => {
    if (bang || !target || target.startsWith('#') || /^[a-z][a-z0-9+.-]*:/i.test(target)) return match;
    let file = target.split('#')[0];
    try {
      file = decodeURI(file);
    } catch {
      return label;
    }
    const resolved = file.startsWith('/')
      ? path.posix.normalize(file.slice(1))
      : path.posix.normalize(path.posix.join(path.posix.dirname(docPath), file));
    const key = resolved.replace(/\/$/, '');
    if (key.startsWith('..') || !existingPaths.has(key)) return label;
    return match;
  });
}

// A table's separator row, such as "| --- | :---: |" or "---|---".
// The end of a sentence in a line: a period, question mark, or exclamation mark, with any
// closing quotes, brackets, or emphasis, before a space or the end. "e.g." and "i.e." are not.
const SENTENCE_END = /(?<!\b(?:e\.g|i\.e|etc|vs))[.!?]["'”’)\]`*_]*(?=\s|$)/g;
const FENCE = /^\s*(```|~~~)/;
const LIST_MARKER = /^\s*([-*+]|\d+[.)])\s+/;

function lastSentenceEnd(line) {
  let end = -1;
  for (const m of line.matchAll(SENTENCE_END)) end = m.index + m[0].length;
  return end;
}

// A reply the model stopped at its output limit (Ollama's done_reason "length"), cut back to
// its last complete sentence or list item: never a partial sentence, list item, heading, or
// code block. An open code block goes whole, a heading with nothing after it goes, and a line
// that ends mid-sentence keeps only its complete sentences; a list item with none goes whole.
function cutToComplete(text) {
  const lines = String(text || '').split('\n');
  let open = -1;
  lines.forEach((line, i) => {
    if (FENCE.test(line)) open = open === -1 ? i : -1;
  });
  if (open !== -1) lines.splice(open);
  while (lines.length) {
    const last = lines[lines.length - 1];
    if (!last.trim() || /^#{1,6}\s/.test(last)) {
      lines.pop();
      continue;
    }
    if (FENCE.test(last) || TABLE_ROW.test(last)) break;
    const end = lastSentenceEnd(last.trimEnd());
    if (end === last.trimEnd().length) break;
    const marker = (LIST_MARKER.exec(last) || [''])[0];
    if (end > marker.length) {
      lines[lines.length - 1] = last.slice(0, end);
      break;
    }
    lines.pop();
  }
  return lines.join('\n');
}

// The text of a reply from a call made withReason, cut back when it stopped at its length limit.
// stats.cutReplies counts those. A plain string, as from a test's chat, is used as it is.
function completeReply(reply, stats = {}) {
  if (!reply || typeof reply !== 'object') return String(reply || '');
  if (reply.doneReason !== 'length') return String(reply.content || '');
  stats.cutReplies = (stats.cutReplies || 0) + 1;
  return cutToComplete(reply.content);
}

const TABLE_SEPARATOR =/^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$/;
const TABLE_ROW = /^\s*\|.*\|\s*$/;

// The lines without any Markdown table outside code blocks: tables come only from the computed
// blocks, never from the model. stats.droppedTables counts the tables dropped.
function dropTables(lines, stats = {}) {
  const drop = new Set();
  let fence = null;
  for (let i = 0; i < lines.length; i++) {
    const fenceMatch = lines[i].match(/^\s*(```|~~~)/);
    if (fenceMatch) {
      if (!fence) fence = fenceMatch[1];
      else if (lines[i].trim().startsWith(fence)) fence = null;
      continue;
    }
    if (fence || drop.has(i)) continue;
    const separated = TABLE_SEPARATOR.test(lines[i]) && i > 0 && lines[i - 1].includes('|') && !drop.has(i - 1);
    // Rows that start and end with a pipe, two or more together, are a table too.
    const piped = TABLE_ROW.test(lines[i]) && i + 1 < lines.length && TABLE_ROW.test(lines[i + 1]);
    if (!separated && !piped) continue;
    let start = separated ? i - 1 : i;
    let end = i;
    while (end + 1 < lines.length && lines[end + 1].trim() && lines[end + 1].includes('|')) end++;
    for (let j = start; j <= end; j++) drop.add(j);
    stats.droppedTables = (stats.droppedTables || 0) + 1;
    i = end;
  }
  return lines.filter((_, i) => !drop.has(i));
}

// Cleans one model reply and gives it exactly one H1: `title`. Web links survive only when
// the repository already has the URL (knownUrls; none by default), and raw HTML never does.
// Tables are dropped. linkStats.droppedLinks and droppedTables count what was dropped.
function cleanMarkdown(raw, { title, docPath = '', existingPaths = null, knownUrls = new Set(), linkStats = {} } = {}) {
  const text = unwrapWholeFence(String(raw || '').replace(/\r\n?/g, '\n').trim());
  const lines = dropTables(trimChatter(text.split('\n')), linkStats);

  const out = [];
  let fence = null;
  let sawH1 = false;
  let dropLevel = 0;
  for (const line of lines) {
    const fenceMatch = line.match(/^\s*(```|~~~)/);
    if (fenceMatch) {
      if (!fence) fence = fenceMatch[1];
      else if (line.trim().startsWith(fence)) fence = null;
      if (!dropLevel) out.push(line);
      continue;
    }
    if (fence) {
      if (!dropLevel && links.keepCodeLine(line, knownUrls, linkStats)) out.push(line);
      continue;
    }
    const heading = line.match(/^(#{1,6})\s+(.*?)(?:\s+#+)?\s*$/);
    if (heading) {
      let level = heading[1].length;
      const headingText = cleanHeadingText(links.cleanProseLine(heading[2], knownUrls, linkStats));
      if (level === 1) {
        if (!sawH1) {
          sawH1 = true;
          continue;
        }
        level = 2;
      }
      if (dropLevel && level <= dropLevel) dropLevel = 0;
      if (DROPPED_HEADING.test(headingText)) {
        dropLevel = level;
        continue;
      }
      if (!dropLevel && headingText) out.push('', `${'#'.repeat(level)} ${sentenceCase(headingText)}`, '');
      continue;
    }
    if (!dropLevel) out.push(links.cleanProseLine(fixLinks(stripEmoji(line), docPath, existingPaths), knownUrls, linkStats));
  }

  // Drop "In conclusion" paragraphs.
  const kept = [];
  let skipping = false;
  fence = null;
  for (let i = 0; i < out.length; i++) {
    const line = out[i];
    if (/^\s*(```|~~~)/.test(line)) fence = fence ? null : true;
    const startsParagraph = i === 0 || !out[i - 1].trim() || /^#/.test(out[i - 1]);
    if (!fence && startsParagraph && CONCLUSION_PARAGRAPH.test(line.trim())) skipping = true;
    if (skipping && !line.trim()) skipping = false;
    if (!skipping) kept.push(line);
  }

  const body = kept.join('\n').replace(/\n{3,}/g, '\n\n').trim();
  return body ? `# ${title}\n\n${body}` : `# ${title}`;
}

function finalizeDoc(markdown) {
  return `${MARKER}\n\n${markdown.replace(/\n{3,}/g, '\n\n').trim()}\n`;
}

function cleanDoc(raw, options) {
  return finalizeDoc(cleanMarkdown(raw, options));
}

