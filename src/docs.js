function componentsTable(layer, fileInfo, docsDir) {
  const rows = layer.files.map((file) => {
    const info = fileInfo.get(file) || {};
    const symbols = (info.symbols || []).slice(0, 6).map((s) => `\`${String(s).replace(/`/g, '')}\``).join(', ');
    return `| [\`${file}\`](${linkPath(docsDir, file)}) | ${tableCell(firstSentence(info.summary))} | ${tableCell(symbols)} |`;
  });
  return ['| File | Purpose | Main definitions |', '| --- | --- | --- |', ...rows].join('\n');
}

function relatedLayers(layer, layers) {
  return layers
    .filter((other) => other.slug !== layer.slug)
    .map((other) => `- [${other.name}](${other.slug}.md): ${other.description}`)
    .join('\n');
}

// `base` is the path from the linking document to the docs folder, such as "docs/".
function layersTable(layers, base = '') {
  const rows = layers.map((layer) => `| [${tableCell(layer.name)}](${base}${layer.slug}.md) | ${tableCell(layer.description)} |`);
  return ['| Layer | Description |', '| --- | --- |', ...rows].join('\n');
}

function scriptsTable(facts) {
  const entries = Object.entries(facts.scripts || {});
  if (!entries.length) return '';
  const run = RUN_SCRIPT[facts.packageManagers.find((pm) => RUN_SCRIPT[pm])] || RUN_SCRIPT.npm;
  const rows = entries.map(([name, command]) => `| \`${run} ${tableCell(name)}\` | \`${tableCell(command)}\` |`);
  return ['| Command | Runs |', '| --- | --- |', ...rows].join('\n');
}

function visibleDirs(file) {
  const dirs = path.posix.dirname(file);
  return dirs === '.' ? [] : dirs.split('/');
}

function directoryTree(paths, { maxDepth = 3, maxLines = 80 } = {}) {
  const root = { dirs: new Map(), files: [] };
  for (const file of paths) {
    const dirs = visibleDirs(file);
    if (dirs.some((d) => SKIP_DIRS.has(d) || d.startsWith('.'))) continue;
    if (!dirs.length) {
      root.files.push(file);
      continue;
    }
    let node = root;
    for (const dir of dirs.slice(0, maxDepth)) {
      if (!node.dirs.has(dir)) node.dirs.set(dir, { dirs: new Map(), files: [] });
      node = node.dirs.get(dir);
    }
  }
  const lines = ['.'];
  const render = (node, prefix) => {
    const entries = [
      ...[...node.dirs.keys()].sort().map((name) => ({ name: `${name}/`, node: node.dirs.get(name) })),
      ...node.files.sort().map((name) => ({ name })),
    ];
    entries.forEach((entry, i) => {
      const last = i === entries.length - 1;
      lines.push(`${prefix}${last ? '└── ' : '├── '}${entry.name}`);
      if (entry.node) render(entry.node, `${prefix}${last ? '    ' : '│   '}`);
    });
  };
  render(root, '');
  if (lines.length > maxLines) return [...lines.slice(0, maxLines - 1), '└── ...'].join('\n');
  return lines.join('\n');
}

// --- Project facts ---

function parseRequirements(text) {
  return text
    .split('\n')
    .map((line) => line.replace(/#.*/, '').trim())
    .filter((line) => line && !line.startsWith('-'))
    .map((line) => line.split(/[\s<>=!~;[]/)[0])
    .filter(Boolean);
}

function pyprojectField(text, field) {
  const section = text.match(/^\[(project|tool\.poetry)\]\s*$([\s\S]*?)(?=^\[|(?![\s\S]))/m);
  if (!section) return '';
  const match = section[2].match(new RegExp(`^\\s*${field}\\s*=\\s*["']([^"']*)["']`, 'm'));
  return match ? match[1] : '';
}

// Facts for the main doc. Only names are taken from .env.example, never values.
function collectProjectFacts(readFile, allFiles) {
  const rootFiles = new Set(allFiles.filter((f) => !f.includes('/')));
  const read = (name) => {
    if (!rootFiles.has(name)) return null;
    try {
      const content = readFile(name);
      return typeof content === 'string' ? content : null;
    } catch {
      return null;
    }
  };
  const facts = {
    name: '', description: '', scripts: {}, dependencies: [], devDependencies: [], engines: {},
    pythonRequirements: [], envVars: [], packageManagers: [], rootReadme: '',
  };

  const pkgText = read('package.json');
  if (pkgText) {
    try {
      const pkg = JSON.parse(pkgText);
      facts.name = typeof pkg.name === 'string' ? pkg.name : '';
      facts.description = typeof pkg.description === 'string' ? pkg.description : '';
      if (pkg.scripts && typeof pkg.scripts === 'object') {
        facts.scripts = Object.fromEntries(Object.entries(pkg.scripts).filter(([, v]) => typeof v === 'string'));
      }
      facts.dependencies = Object.keys(pkg.dependencies || {});
      facts.devDependencies = Object.keys(pkg.devDependencies || {});
      if (pkg.engines && typeof pkg.engines === 'object') facts.engines = pkg.engines;
    } catch {
      // A broken package.json gives no facts.
    }
  }
  const pyproject = read('pyproject.toml');
  if (pyproject) {
    facts.name = facts.name || pyprojectField(pyproject, 'name');
    facts.description = facts.description || pyprojectField(pyproject, 'description');
  }
  const requirements = read('requirements.txt');
  if (requirements) facts.pythonRequirements = parseRequirements(requirements);
  const env = read('.env.example');
  if (env) {
    facts.envVars = [...new Set(
      env.split('\n').map((line) => line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/)).filter(Boolean).map((m) => m[1])
    )];
  }
  facts.packageManagers = [...new Set(PACKAGE_MANAGERS.filter(([file]) => rootFiles.has(file)).map(([, pm]) => pm))];
  if (!facts.packageManagers.length && pkgText) facts.packageManagers = ['npm'];
  const readmeName = [...rootFiles].find((f) => /^readme(\.md|\.markdown|\.txt)?$/i.test(f));
  if (readmeName) facts.rootReadme = (read(readmeName) || '').slice(0, 4000);
  return facts;
}

function describeFacts(facts) {
  const lines = [];
  if (facts.name) lines.push(`Project name: ${facts.name}`);
  if (facts.description) lines.push(`Description: ${facts.description}`);
  if (facts.packageManagers.length) lines.push(`Package manager: ${facts.packageManagers.join(', ')}`);
  if (Object.keys(facts.engines).length) lines.push(`Engines: ${JSON.stringify(facts.engines)}`);
  if (Object.keys(facts.scripts).length) lines.push(`Scripts: ${JSON.stringify(facts.scripts)}`);
  if (facts.dependencies.length) lines.push(`Dependencies: ${facts.dependencies.join(', ')}`);
  if (facts.devDependencies.length) lines.push(`Development dependencies: ${facts.devDependencies.join(', ')}`);
  if (facts.pythonRequirements.length) lines.push(`Python requirements: ${facts.pythonRequirements.join(', ')}`);
  if (facts.envVars.length) lines.push(`Environment variables in .env.example: ${facts.envVars.join(', ')}`);
  return lines.join('\n') || 'None found.';
}

// --- Layers ---

function normalizeFilePath(p) {
  if (typeof p !== 'string' || !p.trim()) return '';
  return path.posix.normalize(p.trim().replace(/\\/g, '/')).replace(/^\.\//, '');
}

function slugify(name) {
  return name
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'layer';
}

function sharedDepth(a, b) {
  let n = 0;
  while (n < a.length && n < b.length && a[n] === b[n]) n++;
  return n;
}

function closestLayer(file, layers) {
  const dirs = visibleDirs(file);
  let best = layers[0];
  let bestDepth = -1;
  for (const layer of layers) {
    for (const other of layer.files) {
      const depth = sharedDepth(dirs, visibleDirs(other));
      if (depth > bestDepth) {
        bestDepth = depth;
        best = layer;
      }
    }
  }
  return best;
}

// Builds layers from model or previous entries, keeping only known files, each in one layer.
function layersFromEntries(entries, known) {
  const layers = [];
  const assigned = new Set();
  for (const entry of Array.isArray(entries) ? entries : []) {
    if (!entry || typeof entry !== 'object') continue;
    const name = titleCase(entry.name);
    if (!name) continue;
    let layer = layers.find((l) => slugify(l.name) === slugify(name));
    if (!layer) {
      layer = { name, description: typeof entry.description === 'string' ? firstSentence(entry.description) : '', files: [] };
      layers.push(layer);
    }
    for (const file of Array.isArray(entry.files) ? entry.files.map(normalizeFilePath) : []) {
      if (known.has(file) && !assigned.has(file)) {
        assigned.add(file);
        layer.files.push(file);
      }
    }
  }
  return layers.filter((l) => l.files.length);
}

// Used when neither the model nor the previous run gives usable layers.
function layersByDirectory(files) {
  const dirs = files.map(visibleDirs);
  let depth = 0;
  while (dirs.length && dirs.every((d) => d.length > depth && d[depth] === dirs[0][depth])) depth++;
  const prefix = dirs.length ? dirs[0].slice(0, depth).join('/') : '';
  const groups = new Map();
  files.forEach((file, i) => {
    const key = dirs[i][depth] || '';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(file);
  });
  let layers = [...groups].map(([key, groupFiles]) => {
    const folder = [prefix, key].filter(Boolean).join('/');
    return {
      name: key ? titleCase(key.replace(/[-_.]+/g, ' ')) : 'Core',
      description: folder ? `Code in the \`${folder}\` folder.` : 'Files at the top level of the project.',
      files: groupFiles,
    };
  });
  if (layers.length > MAX_LAYERS) {
    layers.sort((a, b) => b.files.length - a.files.length);
    const rest = layers.slice(MAX_LAYERS - 1);
    layers = layers.slice(0, MAX_LAYERS - 1);
    layers.push({ name: 'Other', description: 'Files in smaller folders.', files: rest.flatMap((l) => l.files) });
  }
  return layers;
}

function assignSlugs(layers, isTaken = () => false) {
  const used = new Set();
  for (const layer of layers) {
    let base = slugify(layer.name);
    if (RESERVED_SLUGS.has(base)) base = `${base}-layer`;
    let slug = base;
    for (let n = 2; used.has(slug) || isTaken(slug); n++) slug = `${base}-${n}`;
    used.add(slug);
    layer.slug = slug;
  }
}

// Validates the model's layers: known files only, each file in exactly one layer, at most
// seven layers, unique slugs, and missed files placed by the closest shared directory.
function normalizeLayers(raw, files, { previous = [], fileInfo = new Map(), isTaken } = {}) {
  const known = new Set(files.map(normalizeFilePath).filter(Boolean));
  if (!known.size) return [];
  let layers = layersFromEntries(raw && raw.layers, known);
  if (!layers.length) layers = layersFromEntries(previous, known);
  if (!layers.length) layers = layersByDirectory([...known].sort());
  if (layers.length > MAX_LAYERS) {
    const keep = new Set([...layers].sort((a, b) => b.files.length - a.files.length).slice(0, MAX_LAYERS));
    layers = layers.filter((l) => keep.has(l));
  }

  const assigned = new Set(layers.flatMap((l) => l.files));
  for (const file of [...known].sort()) {
    if (!assigned.has(file)) closestLayer(file, layers).files.push(file);
  }
  for (const layer of layers) {
    layer.files.sort();
    if (!layer.description) {
      const summary = layer.files.map((f) => (fileInfo.get(f) || {}).summary).find(Boolean);
      layer.description = summary ? firstSentence(summary) : `Files in the ${layer.name} layer.`;
    }
  }
  assignSlugs(layers, isTaken);
  return layers.map(({ name, slug, description, files: layerFiles }) => ({ name, slug, description, files: layerFiles }));
}

const LAYERS_SCHEMA = {
  type: 'object',
  properties: {
    layers: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          name: { type: 'string' },
          description: { type: 'string' },
          files: { type: 'array', items: { type: 'string' } },
        },
        required: ['name', 'description', 'files'],
      },
    },
  },
  required: ['layers'],
};

function charBudget(contextTokens) {
  return Math.max(4000, (contextTokens - PROMPT_RESERVE_TOKENS - OUTPUT_RESERVE_TOKENS) * CHARS_PER_TOKEN);
}

function fileListing(files, fileInfo, budget) {
  const describe = (detail) => files.map((file) => {
    const info = fileInfo.get(file) || {};
    if (detail === 'paths') return `- ${file}`;
    const summary = detail === 'full' ? String(info.summary || '').trim() : firstSentence(info.summary);
    const symbols = (info.symbols || []).slice(0, 8).join(', ');
    return `- ${file}: ${summary}${symbols ? ` (Defines: ${symbols})` : ''}`;
  }).join('\n');
  for (const detail of ['full', 'short', 'paths']) {
    const listing = describe(detail);
    if (listing.length <= budget || detail === 'paths') return listing;
  }
  return '';
}

function layersPrompt(files, fileInfo, previous, contextTokens) {
  const previousText = previous.length
    ? JSON.stringify(previous.map(({ name, description, files: f }) => ({ name, description, files: f })), null, 1)
    : 'None.';
  const listing = fileListing(files, fileInfo, charBudget(contextTokens) - previousText.length);
  return [
    { role: 'system', content: `You document the architecture of software projects.\n\n${STYLE_RULES}` },
    {
      role: 'user',
      content: `Group the files of this project into 2 to 7 architecture layers. A layer is a set of files that share one responsibility, such as "User Interface", "API Routes", or "Data Access".

For each layer, give:
- name: a short name in title case.
- description: one sentence that says what the layer does.
- files: the paths of its files, exactly as listed below.

Put every file in exactly one layer.

Previous layers. Keep them unless the structure of the project clearly changed:
${previousText}

Files:
${listing}`,
    },
  ];
}

// `call` sends one request to the docs model and returns the reply text.
async function planLayers({ files, fileInfo, previousLayers = [], call, contextTokens, isTaken, errors = [] }) {
  let raw = null;
  try {
    const content = await call('layers', {
      messages: layersPrompt(files, fileInfo, previousLayers, contextTokens),
      format: LAYERS_SCHEMA,
      options: { temperature: 0.2, seed: 42, num_ctx: contextTokens },
    });
    raw = JSON.parse(content);
  } catch (err) {
    errors.push(`layers: ${err.message}`);
  }
  return normalizeLayers(raw, files, { previous: previousLayers, fileInfo, isTaken });
}

// Calls the docs model, switching to the fallback model for the rest of the run once the
// docs model cannot load. `lastUsedFallback` says whether the latest reply came from the
// fallback model. Errors about the switch go to `errors`.
function createCaller({ chat = ollama.chat, model, fallbackModel = null, host, errors = [] }) {
  const caller = { model, activeModel: model, fallbackUsed: false, lastUsedFallback: false, errors };
  caller.call = async (label, request) => {
    try {
      const content = await chat({ ...request, model: caller.activeModel, host });
      caller.lastUsedFallback = caller.activeModel !== model;
      return content;
    } catch (err) {
      if (!fallbackModel || caller.activeModel === fallbackModel || !isLoadError(err)) throw err;
      errors.push(`${label}: the docs model ${model} could not load (${err.message.slice(0, 200)}); switched to ${fallbackModel}`);
      caller.activeModel = fallbackModel;
      caller.fallbackUsed = true;
      const content = await chat({ ...request, model: caller.activeModel, host });
      caller.lastUsedFallback = true;
      return content;
    }
  };
  return caller;
}

// Errors where Ollama could not load or run the model, usually because the runner is out of memory.
const LOAD_ERROR = /out of memory|requires more system memory|not enough memory|insufficient memory|failed to load|unable to load|error loading model|llama runner process (has )?terminated|signal: killed|cudaMalloc|\bOOM\b/i;

function isLoadError(err) {
  return LOAD_ERROR.test(String(err && err.message));
}

// --- Layer docs ---

function excerpts(layer, fileInfo, readSource, budget) {
  const parts = [];
  let remaining = budget;
  const files = [...layer.files].sort((a, b) => ((fileInfo.get(b) || {}).symbols || []).length - ((fileInfo.get(a) || {}).symbols || []).length);
  files.forEach((file, i) => {
    const share = Math.floor(remaining / (files.length - i));
    const source = readSource(file);
    if (!source || share < 300) return;
    let excerpt = source.length > share ? source.slice(0, source.lastIndexOf('\n', share) > 0 ? source.lastIndexOf('\n', share) : share) : source;
    if (excerpt.length < source.length) excerpt += '\n...';
    const block = `#### ${file}\n\`\`\`${path.posix.extname(file).slice(1)}\n${excerpt}\n\`\`\``;
    parts.push(block);
    remaining -= block.length;
  });
  return parts.join('\n\n');
}

function layerDocPrompt({ layer, layers, fileInfo, facts, readSource, contextTokens, projectName }) {
  const others = layers.filter((l) => l.slug !== layer.slug).map((l) => `- ${l.name}: ${l.description}`).join('\n') || 'None.';
  const summaries = layer.files.map((file) => {
    const info = fileInfo.get(file) || {};
    const symbols = (info.symbols || []).join(', ');
    return `- ${file}: ${String(info.summary || '').trim()}${symbols ? ` (Defines: ${symbols})` : ''}`;
  }).join('\n');
  const head = `Write the documentation page for the "${layer.name}" layer of ${projectName}.

Use exactly this structure:

# ${layer.name}

One paragraph that says what this layer is for.

## Overview

## Responsibilities

A bulleted list.

## How it works

## Configuration

Include this section only if the material shows settings, environment variables, or configuration files that this layer reads. Otherwise leave it out.

Do not add other sections. Do not add a table of files or a list of related layers; those are added separately.

Layer description: ${layer.description}

Other layers:
${others}

Project configuration:
${describeFacts(facts)}

Files in this layer:
${summaries}

Source excerpts:
`;
  const sources = excerpts(layer, fileInfo, readSource, charBudget(contextTokens) - head.length);
  return [
    { role: 'system', content: `You write developer documentation.\n\n${STYLE_RULES}` },
    { role: 'user', content: head + (sources || 'None.') },
  ];
}

// Assembles a layer doc from the model's reply and the generated parts.
function buildLayerDoc(raw, { layer, layers, fileInfo, docsDir = 'docs', existingPaths = null }) {
  const docPath = `${docsDir}/${layer.slug}.md`;
  const cleaned = cleanMarkdown(raw, { title: layer.name, docPath, existingPaths });
  const { intro, sections } = splitSections(cleaned);
  const bodies = arrangeSections(sections, LAYER_SECTIONS, { extrasInto: 'how', generated: LAYER_GENERATED });
  const { first, rest } = splitIntro(intro);

  const overview = [rest, bodies.get('overview')].filter(Boolean).join('\n\n') || layer.description;
  const responsibilities = bodies.get('responsibilities')
    || layer.files.map((f) => firstSentence((fileInfo.get(f) || {}).summary)).filter((s) => s !== '').map((s) => `- ${s}`).join('\n');
  const configuration = bodies.get('configuration');
  const backLink = `- [Project README](${linkPath(docsDir, 'README.md')}): the overview of the whole project and every layer.`;
  const related = [backLink, relatedLayers(layer, layers)].filter(Boolean).join('\n');

  const parts = [`# ${layer.name}`, first || layer.description, '## Overview', overview];
  if (responsibilities) parts.push('## Responsibilities', responsibilities);
  parts.push('## Key components', componentsTable(layer, fileInfo, docsDir));
  if (bodies.get('how')) parts.push('## How it works', bodies.get('how'));
  if (configuration && !saysNone(configuration)) parts.push('## Configuration', configuration);
  parts.push('## Related layers', related);
  return finalizeDoc(parts.join('\n\n'));
}

// --- Orchestration ---

function sameLayer(a, b) {
  return a && b && a.name === b.name && a.description === b.description &&
    a.files.length === b.files.length && a.files.every((f, i) => f === b.files[i]);
}

function pathsWithDirs(paths) {
  const all = new Set();
  for (const p of paths) {
    all.add(p);
    let dir = path.posix.dirname(p);
    while (dir !== '.' && !all.has(dir)) {
      all.add(dir);
      dir = path.posix.dirname(dir);
    }
  }
  return all;
}

function fsReader(root) {
  return (relPath) => {
    try {
      return fs.readFileSync(path.join(root, relPath), 'utf8');
    } catch {
      return null;
    }
  };
}

function sameFileSet(layers, paths) {
  const previous = layers.flatMap((l) => l.files).sort();
  const current = [...paths].sort();
  return previous.length === current.length && previous.every((f, i) => f === current[i]);
}

// Plans the content of the layer docs. Nothing is written to disk here; see writeDocs.
// files: [{ path, summary, symbols, text? }] for every documented source file.
// changedFiles: a Set of changed paths, or null to regenerate everything.
// staleSlugs: docs that a previous run could not write ("README" for the main doc).
// caller: from createCaller; otherwise one is made from chat, model, fallbackModel, and host.
// deadline: a time in ms after which no new doc is started.
// Returns { layers, replanned, docs: [{ path, content, fallback }], pending: [{ path, slug, reason }],
//   skipped: [{ path, reason }], removed: [path], errors, fallbackUsed, facts, projectName,
//   readmeNeeded }. readmeNeeded says whether the README's Docturnal sections need new prose.
// A docs/README.md with the marker, the main doc of earlier versions, is removed.
async function generateDocs({
  files,
  allFiles,
  readFile,
  root,
  docsDir = 'docs',
  model,
  fallbackModel = null,
  host,
  contextTokens = 8192,
  chat = ollama.chat,
  previousLayers = [],
  changedFiles = null,
  staleSlugs = [],
  deadline = Infinity,
  now = Date.now,
  projectName,
  caller: givenCaller,
}) {
  const read = readFile || fsReader(root || '.');
  const repoFiles = allFiles || files.map((f) => f.path);
  const fileInfo = new Map(files.map((f) => [normalizeFilePath(f.path), f]));
  const sourcePaths = [...fileInfo.keys()];
  const docPathFor = (slug) => `${docsDir}/${slug}.md`;
  const humanWritten = (docPath) => {
    const existing = read(docPath);
    return existing !== null && !hasMarker(existing);
  };
  // Once the docs model fails to load, the rest of the run uses the fallback model.
  const caller = givenCaller || createCaller({ chat, model, fallbackModel, host });
  const call = caller.call;
  const result = {
    layers: [], replanned: false, docs: [], pending: [], skipped: [], removed: [], errors: caller.errors, fallbackUsed: false,
    facts: null, projectName: '', readmeNeeded: false,
  };
  const stale = new Set(staleSlugs);
  const facts = collectProjectFacts(read, repoFiles);
  result.facts = facts;
  result.projectName = facts.name || projectName || path.basename(path.resolve(root || '.'));
  // The main document is README.md at the repository root now.
  const legacyReadme = `${docsDir}/README.md`;
  if (hasMarker(read(legacyReadme))) result.removed.push(legacyReadme);

  if (!sourcePaths.length) {
    for (const old of previousLayers) {
      if (hasMarker(read(docPathFor(old.slug)))) result.removed.push(docPathFor(old.slug));
    }
    result.readmeNeeded = previousLayers.length > 0;
    return result;
  }

  const isTaken = (slug) => humanWritten(docPathFor(slug));
  let layers;
  if (previousLayers.length && sameFileSet(previousLayers, sourcePaths)) {
    layers = normalizeLayers({ layers: previousLayers }, sourcePaths, { previous: previousLayers, fileInfo, isTaken });
  } else {
    result.replanned = true;
    layers = await planLayers({ files: sourcePaths, fileInfo, previousLayers, call, contextTokens, isTaken, errors: result.errors });
  }
  result.layers = layers;

  const name = result.projectName;
  const existingPaths = pathsWithDirs([...repoFiles, 'README.md', ...layers.map((l) => docPathFor(l.slug))]);
  const readSource = (file) => {
    const info = fileInfo.get(file);
    return info && typeof info.text === 'string' ? info.text : read(file);
  };
  const previousBySlug = new Map(previousLayers.map((l) => [l.slug, l]));
  const changed = (file) => changedFiles === null || changedFiles.has(file);
  const docOptions = { temperature: 0.3, seed: 42, num_ctx: contextTokens };

  let anyLayerWritten = false;
  for (const layer of layers) {
    const docPath = docPathFor(layer.slug);
    const previous = previousBySlug.get(layer.slug);
    const needed = changedFiles === null || stale.has(layer.slug) || !sameLayer(layer, previous) ||
      layer.files.some(changed) || read(docPath) === null;
    if (!needed) continue;
    if (now() > deadline) {
      result.pending.push({ path: docPath, slug: layer.slug, reason: 'time budget' });
      continue;
    }
    try {
      const content = await call(docPath, {
        messages: layerDocPrompt({ layer, layers, fileInfo, facts, readSource, contextTokens, projectName: name }),
        options: docOptions,
      });
      result.docs.push({ path: docPath, content: buildLayerDoc(content, { layer, layers, fileInfo, docsDir, existingPaths }), fallback: caller.lastUsedFallback });
      anyLayerWritten = true;
    } catch (err) {
      result.errors.push(`${docPath}: ${err.message}`);
      result.pending.push({ path: docPath, slug: layer.slug, reason: 'the model did not respond' });
    }
  }

  const factFiles = ['package.json', 'requirements.txt', 'pyproject.toml', '.env.example'];
  const layerSetChanged = layers.length !== previousLayers.length || layers.some((l) => !sameLayer(l, previousBySlug.get(l.slug)));
  result.readmeNeeded = changedFiles === null || stale.has('README') || anyLayerWritten || layerSetChanged ||
    factFiles.some((f) => changedFiles.has(f));

  const currentSlugs = new Set(layers.map((l) => l.slug));
  for (const old of previousLayers) {
    const docPath = docPathFor(old.slug);
    if (!currentSlugs.has(old.slug) && hasMarker(read(docPath))) result.removed.push(docPath);
  }
  result.fallbackUsed = caller.fallbackUsed;
  return result;
}

// Writes planned docs under root. Never overwrites or deletes a file without the marker.
function writeDocs({ root, docs = [], removed = [] }) {
  const written = [];
  const skipped = [];
  const deleted = [];
  for (const doc of docs) {
    const full = path.join(root, doc.path);
    let existing = null;
    try {
      existing = fs.readFileSync(full, 'utf8');
    } catch {
      // No file yet.
    }
    if (existing !== null && !hasMarker(existing)) {
      skipped.push({ path: doc.path, reason: 'written by a person (no Docturnal marker)' });
      continue;
    }
    if (!hasMarker(doc.content)) throw new Error(`Refusing to write ${doc.path} without the Docturnal marker`);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, doc.content);
    written.push(doc.path);
  }
  for (const docPath of removed) {
    const full = path.join(root, docPath);
    try {
      if (hasMarker(fs.readFileSync(full, 'utf8'))) {
        fs.unlinkSync(full);
        deleted.push(docPath);
      }
    } catch {
      // Already gone.
    }
  }
  return { written, skipped, deleted };
}

