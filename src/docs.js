function componentsTable(layer, fileInfo, docsDir) {
  const rows = layer.files.map((file) => {
    const info = fileInfo.get(file) || {};
    const symbols = (info.symbols || []).slice(0, 6).map((s) => `\`${String(s).replace(/`/g, '')}\``).join(', ');
    return `| [\`${file}\`](${linkPath(docsDir, file)}) | ${tableCell(firstSentence(info.summary))} | ${tableCell(symbols)} |`;
  });
  return ['| File | Purpose | Main definitions |', '| --- | --- | --- |', ...rows].join('\n');
}

function relatedLayers(layer, layers) {
  return layers
    .filter((other) => other.slug !== layer.slug)
    .map((other) => `- [${other.name}](${other.slug}.md): ${other.description}`)
    .join('\n');
}

// `base` is the path from the linking document to the docs folder, such as "docs/".
function layersTable(layers, base = '') {
  const rows = layers.map((layer) => `| [${tableCell(layer.name)}](${base}${layer.slug}.md) | ${tableCell(layer.description)} |`);
  return ['| Layer | Description |', '| --- | --- |', ...rows].join('\n');
}

function scriptsTable(facts) {
  const entries = Object.entries(facts.scripts || {});
  if (!entries.length) return '';
  const run = RUN_SCRIPT[facts.packageManagers.find((pm) => RUN_SCRIPT[pm])] || RUN_SCRIPT.npm;
  const rows = entries.map(([name, command]) => `| \`${run} ${tableCell(name)}\` | \`${tableCell(command)}\` |`);
  return ['| Command | Runs |', '| --- | --- |', ...rows].join('\n');
}

function visibleDirs(file) {
  const dirs = path.posix.dirname(file);
  return dirs === '.' ? [] : dirs.split('/');
}

function directoryTree(paths, { maxDepth = 3, maxLines = 80 } = {}) {
  const root = { dirs: new Map(), files: [] };
  for (const file of paths) {
    const dirs = visibleDirs(file);
    if (dirs.some((d) => SKIP_DIRS.has(d) || d.startsWith('.'))) continue;
    if (!dirs.length) {
      root.files.push(file);
      continue;
    }
    let node = root;
    for (const dir of dirs.slice(0, maxDepth)) {
      if (!node.dirs.has(dir)) node.dirs.set(dir, { dirs: new Map(), files: [] });
      node = node.dirs.get(dir);
    }
  }
  const lines = ['.'];
  const render = (node, prefix) => {
    const entries = [
      ...[...node.dirs.keys()].sort().map((name) => ({ name: `${name}/`, node: node.dirs.get(name) })),
      ...node.files.sort().map((name) => ({ name })),
    ];
    entries.forEach((entry, i) => {
      const last = i === entries.length - 1;
      lines.push(`${prefix}${last ? '└── ' : '├── '}${entry.name}`);
      if (entry.node) render(entry.node, `${prefix}${last ? '    ' : '│   '}`);
    });
  };
  render(root, '');
  if (lines.length > maxLines) return [...lines.slice(0, maxLines - 1), '└── ...'].join('\n');
  return lines.join('\n');
}

