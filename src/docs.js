// Splits cleaned Markdown into the intro (before the first H2) and its H2 sections.
function splitSections(markdown) {
  const lines = markdown.split('\n');
  const intro = [];
  const sections = [];
  let current = null;
  let fence = false;
  for (const line of lines) {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence;
    if (!fence && /^# /.test(line)) continue;
    const heading = !fence && line.match(/^## (.*)$/);
    if (heading) {
      current = { heading: heading[1].trim(), lines: [] };
      sections.push(current);
    } else if (current) {
      current.lines.push(line);
    } else {
      intro.push(line);
    }
  }
  return {
    intro: intro.join('\n').trim(),
    sections: sections.map((s) => ({ heading: s.heading, body: s.lines.join('\n').trim() })),
  };
}

function headingKey(heading) {
  return heading.toLowerCase().replace(/[^a-z ]/g, '').replace(/\s+/g, ' ').trim();
}

// Maps the model's sections onto the canonical ones. Unknown sections become subsections
// of `extrasInto`; sections that code generates are dropped.
function arrangeSections(sections, canonical, { extrasInto, generated }) {
  const bodies = new Map(canonical.map((c) => [c.key, []]));
  for (const section of sections) {
    const key = headingKey(section.heading);
    if (generated.some((g) => key === g)) continue;
    const match = canonical.find((c) => c.aliases.includes(key));
    if (match) bodies.get(match.key).push(section.body);
    else if (extrasInto && section.body) bodies.get(extrasInto).push(`### ${section.heading}\n\n${section.body}`);
  }
  return new Map([...bodies].map(([key, parts]) => [key, parts.filter(Boolean).join('\n\n').trim()]));
}

// Splits the intro into its first paragraph and anything after it.
function splitIntro(intro) {
  const paragraphs = intro.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
  return { first: paragraphs[0] || '', rest: paragraphs.slice(1).join('\n\n') };
}

function removeSubsections(body, names) {
  const lines = body.split('\n');
  const out = [];
  let dropping = false;
  for (const line of lines) {
    const heading = line.match(/^#{3,6} (.*)$/);
    if (heading) dropping = names.includes(headingKey(heading[1]));
    if (!dropping) out.push(line);
  }
  return out.join('\n').trim();
}

