run_docturnal run1b
expect_count "run 1b comments" '"kind":"comments"' 4
expect_count "run 1b comment model only for comments" '"model":"comment-model","kind":"comments"' 4
# The docs model is loaded once, then checks the comments in each commented file.
expect_count "run 1b docs model loaded before the check" '"model":"docs-model","kind":"load"' 1
expect_count "run 1b accuracy checks with the docs model" '"model":"docs-model","kind":"accuracy"' 4
expect_count "run 1b summaries" '"kind":"summary"' 0
contains "$(remote_file .docturnal/state.json)" '"comments": [' "run 1b state.json records Docturnal's comments"
LAST_RUN="$(remote_file .docturnal/last-run.md)"
[ "$(head -n 1 <<< "$LAST_RUN")" = "# Docturnal: comments and documentation" ] || fail "run 1b title"
for f in src/api/users.js src/api/orders.js src/db/client.js lib/util.py; do contains "$LAST_RUN" "\`$f\`" "run 1b last-run.md"; done
contains "$LAST_RUN" '| `src/api/users.js` | 1 | Yes (TypeScript) |' "run 1b last-run.md"
contains "$LAST_RUN" '| `lib/util.py` | 1 | Yes (Python) |' "run 1b last-run.md"
contains "$LAST_RUN" '- **Comments:** 4 of 4 files commented at the medium level.' "run 1b last-run.md"
contains "$LAST_RUN" '- **This pull request:** documentation for the whole project and batch 1 of existing code, 4 files' "run 1b last-run.md"
contains "$LAST_RUN" '- **Next:** comments on new and changed code. Every existing file is commented.' "run 1b last-run.md"
contains "$(remote_file src/api/users.js)" '// Keeps the getUser logic in one place for callers.' "run 1b users.js"
grep -q 'update branch existing' "$RUN_LOG" || fail "run 1b did not add to the open pull request"
pass "run 1b adds batch 1 of existing code to the open pull request"

merge_pull_request

# --- Run 2: no changes, does nothing ---
BEFORE="$(remote_sha)"
run_docturnal run2
[ "$(remote_sha)" = "$BEFORE" ] || fail "run 2 pushed although nothing changed"
expect_count "run 2" '"kind"' 0
grep -q 'nothing changed since the last run' "$RUN_LOG" || fail "run 2 did not report that nothing changed"
pass "run 2 with no changes makes no model calls and pushes nothing"

# --- Run 3: one file edited ---
cat >> "$WORK/seed/src/db/client.js" <<'EOF'

export function disconnect(client) {
  return { ...client, connected: false };
}
EOF
seed_commit "Add disconnect"
run_docturnal run3
expect_count "run 3 comments" '"kind":"comments"' 1
expect_count "run 3 comments for the edited file" '"kind":"comments","file":"src/db/client.js"' 1
expect_count "run 3 layers" '"kind":"layers"' 0
expect_count "run 3 layer docs" '"kind":"layer-doc"' 1
expect_count "run 3 main doc" '"kind":"readme"' 1
LAST_RUN="$(remote_file .docturnal/last-run.md)"
contains "$LAST_RUN" '`src/db/client.js`' "run 3 last-run.md"
lacks "$LAST_RUN" 'src/api/users.js' "run 3 last-run.md"
lacks "$LAST_RUN" 'lib/util.py' "run 3 last-run.md"
contains "$LAST_RUN" '- Updated `docs/db-code.md`' "run 3 last-run.md"
# The main doc's prose comes out the same, so README.md stays as it is.
lacks "$LAST_RUN" '## README' "run 3 last-run.md"
