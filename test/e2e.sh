run_docturnal run1
[ "$(remote_sha)" != none ] || fail "run 1 did not push docturnal/update"
expect_count "run 1 summaries" '"kind":"summary"' 4
expect_count "run 1 summaries with the comment model" '"model":"comment-model","kind":"summary"' 4
expect_count "run 1 comments" '"kind":"comments"' 0
expect_count "run 1 accuracy checks" '"kind":"accuracy"' 0
expect_count "run 1 layers" '"kind":"layers"' 1
expect_count "run 1 layer docs" '"kind":"layer-doc"' 3
expect_count "run 1 main doc" '"kind":"readme"' 1
LAST_RUN="$(remote_file .docturnal/last-run.md)"
[ "$(head -n 1 <<< "$LAST_RUN")" = "# Docturnal: documentation" ] || fail "run 1 title: $(head -n 1 <<< "$LAST_RUN")"
contains "$LAST_RUN" '- **Documentation:** complete, with 3 layer documents and the README.' "run 1 last-run.md"
contains "$LAST_RUN" '- **Comments:** 0 of 4 files commented at the medium level.' "run 1 last-run.md"
contains "$LAST_RUN" '- **This pull request:** documentation for the whole project.' "run 1 last-run.md"
contains "$LAST_RUN" '- **Next:** comments on existing code in batches of up to 15 files, starting with batch 1 and the most important files. 4 existing files are left.' "run 1 last-run.md"
lacks "$LAST_RUN" '## Comments added' "run 1 last-run.md"
for f in src/api/users.js src/api/orders.js src/db/client.js lib/util.py; do
  [ "$(remote_file "$f")" = "$(git -C "$WORK/seed" show "HEAD:$f")" ] || fail "run 1 changed $f"
done
contains "$(remote_file .docturnal/state.json)" '"docsComplete": true' "run 1 state.json"
contains "$LAST_RUN" '- Removed `docs/README.md` because the main document is now `README.md` at the repository root' "run 1 last-run.md"
contains "$LAST_RUN" '- Updated: "Introduction", "Overview", "Architecture", "Getting started", "Project structure"' "run 1 last-run.md"
README="$(remote_file README.md)"
contains "$README" '<!-- This README is maintained by Docturnal. Your additions and deletions are kept. -->' "run 1 README.md"
lacks "$README" '<!-- Generated by Docturnal.' "run 1 README.md"
contains "$README" '| [Api Code](docs/api-code.md) |' "run 1 README.md"
contains "$README" '<!-- docturnal:tree -->' "run 1 README.md"
remote_file docs/README.md >/dev/null 2>&1 && fail "run 1 kept the old docs/README.md"
contains "$(remote_file .docturnal/readme.json)" '"owner": "docturnal"' "run 1 readme.json"
contains "$(remote_file docs/db-code.md)" '- [Project README](../README.md)' "run 1 docs/db-code.md"
contains "$LAST_RUN" '- Updated `docs/api-code.md`' "run 1 last-run.md"
contains "$LAST_RUN" '- Docs model: `docs-model`' "run 1 last-run.md"
contains "$(remote_file docs/db-code.md)" '<!-- Generated by Docturnal.' "run 1 docs/db-code.md"
STATE="$(remote_file .docturnal/state.json)"
for f in src/api/users.js src/api/orders.js src/db/client.js lib/util.py package.json; do contains "$STATE" "\"$f\"" "run 1 state.json"; done
COMMIT_AUTHOR="$(git --git-dir="$WORK/remote.git" log -1 --format='%an <%ae>' docturnal/update)"
[ "$COMMIT_AUTHOR" = "github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>" ] || fail "run 1 commit author was $COMMIT_AUTHOR"
pass "run 1 documents every file and comments none, in a docs-only pull request"

